//go:build linux && !android

package tunhelper

import (
	"encoding/json"
	"errors"
	"os"
	"os/exec"
	"strings"
)

// dnsBackupFile is in a root-only directory, so it survives a crash for the
// next helper to restore.
const (
	dnsBackupFile = "/run/zeusvpn-dns.json"
	resolvConf    = "/etc/resolv.conf"
)

type dnsBackup struct {
	// Link is set when systemd-resolved was configured for the adapter.
	Link string `json:"link,omitempty"`
	// Otherwise /etc/resolv.conf was replaced: its old contents, or the
	// target when it was a symbolic link.
	Resolv  []byte `json:"resolv,omitempty"`
	Symlink string `json:"symlink,omitempty"`
}

func usesResolved() bool {
	if _, err := exec.LookPath("resolvectl"); err != nil {
		return false
	}
	b, err := os.ReadFile(resolvConf)
	return err == nil && strings.Contains(string(b), "127.0.0.53")
}

func saveBackup(b dnsBackup) error {
	data, _ := json.Marshal(b)
	return os.WriteFile(dnsBackupFile, data, 0o600)
}

// setDNS sends all DNS lookups to the VPN's DNS address, which the adapter
// answers with DNS over HTTPS through the tunnel.
func setDNS(ifname, server string) error {
	if usesResolved() {
		if err := saveBackup(dnsBackup{Link: ifname}); err != nil {
			return err
		}
		if out, err := exec.Command("resolvectl", "dns", ifname, server).CombinedOutput(); err != nil {
			return errors.New(strings.TrimSpace(string(out)))
		}
		exec.Command("resolvectl", "domain", ifname, "~.").Run()
		exec.Command("resolvectl", "default-route", ifname, "true").Run()
		exec.Command("resolvectl", "flush-caches").Run()
		return nil
	}
	var b dnsBackup
	if target, err := os.Readlink(resolvConf); err == nil {
		b.Symlink = target
	} else if data, err := os.ReadFile(resolvConf); err == nil {
		b.Resolv = data
	} else {
		return err
	}
	if err := saveBackup(b); err != nil {
		return err
	}
	os.Remove(resolvConf)
	return os.WriteFile(resolvConf, []byte("# Generated by Zeus VPN; restored on disconnect.\nnameserver "+server+"\n"), 0o644)
}

func restoreDNS() {
	data, err := os.ReadFile(dnsBackupFile)
	if err != nil {
		return
	}
	var b dnsBackup
	if json.Unmarshal(data, &b) == nil {
		switch {
		case b.Link != "":
			// Usually a no-op: the settings vanish with the adapter.
			exec.Command("resolvectl", "revert", b.Link).Run()
			exec.Command("resolvectl", "flush-caches").Run()
		case b.Symlink != "":
			os.Remove(resolvConf)
			os.Symlink(b.Symlink, resolvConf)
		case len(b.Resolv) > 0:
			os.WriteFile(resolvConf, b.Resolv, 0o644)
		}
	}
	os.Remove(dnsBackupFile)
}
